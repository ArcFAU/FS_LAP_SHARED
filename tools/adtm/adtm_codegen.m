function adtm_codegen(options)
%ADTM_CODEGEN Compiles the team's Advanced Dual Track Model into C++ for FS Lap (MATLAB Coder).
%   Run again whenever the ADTM or its vehicle file changes. Writes the generated code to
%   FSLapUE\Plugins\HoMoLapPhysics\Source\HoMoLapPhysics\Private\ADTM and the state and output indices to adtm_indices.h.
%   Options: AdtmRoot (env FSLAP_ADTM_ROOT or D:\FSLap_VD\advanced-dual-track-model), Vehicle ("FAUmaxTau.m"),
%   EnvConditions ("default_mu0.7"), Mex (true: build a MEX in tools\adtm for checking against MATLAB instead).
arguments
    options.AdtmRoot (1, 1) string = defaultRoot()
    options.Vehicle (1, 1) string = "FAUmaxTau.m"
    options.EnvConditions (1, 1) string = "default_mu0.7"
    options.Mex (1, 1) logical = false
end
here = fileparts(mfilename('fullpath'));
project = matlab.project.rootProject;
if isempty(project) || ~strcmpi(string(project.RootFolder), options.AdtmRoot)
    openProject(options.AdtmRoot);
end
opts = struct('vehicle', char(options.Vehicle), 'envConditions', char(options.EnvConditions), 'tireModel', 2, 'tireDyn', true, ...
    'damperModel', 1, 'aeromap', false, 'isSimulink', false, 'forceSkidPad', false, 'driver_separated', false, 'use3DRoad', false);
[xNames, outNames] = f_getIndiceNaming();
P.nStates = numel(fieldnames(xNames)); P.nOutputs = numel(fieldnames(outNames));
opts.x_0 = zeros(P.nStates, 1);
veh = f_vehicleParameters(opts);
names = fieldnames(veh);
P.veh = rmfield(veh, names(structfun(@iscell, veh)));   % file names of the tyres: not needed in the code
tires = cellfun(@f_tireParameters, veh.tires(1:4), 'UniformOutput', false);
[P.tFL, P.tFR, P.tRL, P.tRR] = tires{:};
P.env = f_environmentParameters(opts.envConditions);
P.road = struct('x', [0 1], 'y', [0 1], 'Z', zeros(2), 'Mu', ones(2));   % unused: flat road (use3DRoad false)
P.opts = opts;
P.optsTorque = opts;
P.optsTorque.isSimulink = true;   % adtm_step_torque: the four motor torques come from outside (a VCU), as in the ADTM's Simulink version
P.source = sprintf('%s, %s, %s', options.AdtmRoot, options.Vehicle, options.EnvConditions);
save(fullfile(here, 'adtm_params.mat'), '-struct', 'P');

addpath(here);
args = {zeros(P.nStates, 1), zeros(6, 1), zeros(9, 1), 0, 0};
argsTorque = {zeros(P.nStates, 1), zeros(10, 1), zeros(9, 1), 0, 0};   % u with the four motor torques (adtm_step_torque)
if options.Mex
    codegen('-config:mex', '-d', fullfile(tempdir, 'adtm_mex'), '-o', fullfile(here, 'adtm_step_mex'), 'adtm_step', '-args', args);
    codegen('-config:mex', '-d', fullfile(tempdir, 'adtm_mex_torque'), '-o', fullfile(here, 'adtm_step_torque_mex'), 'adtm_step_torque', '-args', argsTorque);
    return
end
out = fullfile(here, '..', '..', 'FSLapUE', 'Plugins', 'HoMoLapPhysics', 'Source', 'HoMoLapPhysics', 'Private', 'ADTM');
cfg = coder.config('lib');
cfg.TargetLang = 'C++'; cfg.CppNamespace = 'adtm'; cfg.GenerateReport = false; cfg.GenCodeOnly = true; cfg.GenerateMakefile = false;   % the sources only: Unreal and MSVC build them
cfg.FilePartitionMethod = 'SingleFile'; cfg.GenerateExampleMain = 'DoNotGenerate'; cfg.SupportNonFinite = true;
cfg.HardwareImplementation.ProdHWDeviceType = 'Intel->x86-64 (Windows64)';   % self-contained rtwtypes.h (the MATLAB host target includes MATLAB's tmwtypes.h)
codegen('-config', cfg, '-d', fullfile(tempdir, 'adtm_lib'), 'adtm_step', '-args', args, 'adtm_step_torque', '-args', argsTorque, 'adtm_init', '-args', {zeros(9, 1)}, 'adtm_constants');
% only the sources and headers, flat, into the plugin
if isfolder(out), rmdir(out, 's'); end
mkdir(out);
files = [dir(fullfile(tempdir, 'adtm_lib', '*.cpp')); dir(fullfile(tempdir, 'adtm_lib', '*.h'))];
for f = files.', copyfile(fullfile(f.folder, f.name), out); end
writeIndices(fullfile(out, 'adtm_indices.h'), xNames, outNames, P.source);
fprintf('ADTM_CODEGEN_OK %d files to %s\n', numel(files) + 1, out);
end

function writeIndices(file, xNames, outNames, source)
fid = fopen(file, 'w');
fprintf(fid, '// Generated by tools/adtm/adtm_codegen.m from %s. 0-based indices into the ADTM state and output vectors.\n#pragma once\nnamespace adtm::index\n{\n', strrep(source, '\', '/'));
fprintf(fid, '\tconstexpr int nStates = %d;\n\tconstexpr int nOutputs = %d;\n', max(struct2array(xNames)), max(struct2array(outNames)));
fprintf(fid, '\tconstexpr const char* source = "%s";\n', strrep(source, '\', '/'));
for n = fieldnames(xNames).', fprintf(fid, '\tconstexpr int x_%s = %d;\n', n{1}, xNames.(n{1}) - 1); end
for n = fieldnames(outNames).', fprintf(fid, '\tconstexpr int out_%s = %d;\n', n{1}, outNames.(n{1}) - 1); end
fprintf(fid, '}\n');
fclose(fid);
end

function root = defaultRoot()
root = string(getenv('FSLAP_ADTM_ROOT'));
if root == "", root = "D:\FSLap_VD\advanced-dual-track-model"; end
end
